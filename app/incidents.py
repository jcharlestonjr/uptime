"""Incident manager: lifecycle, auto post-mortem drafts, SLA tracking."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timedelta
from typing import Any

from .core import Incident, Monitor, CheckResult


@dataclass
class SLA:
    target_uptime_pct: float = 99.9
    window_days: int = 30


class IncidentManager:
    """Manages incident lifecycle and generates post-mortem drafts."""

    def __init__(self, sla: SLA | None = None):
        self.sla = sla or SLA()
        self.incidents: list[Incident] = []

    def open_incident(self, monitor: Monitor, cause: str, started_at: datetime) -> Incident:
        inc = Incident(id="", monitor_id=monitor.id, started_at=started_at, cause=cause)
        self.incidents.append(inc)
        return inc

    def resolve_incident(self, incident: Incident, resolved_at: datetime,
                         checks: list[CheckResult] | None = None) -> Incident:
        incident.resolved_at = resolved_at
        if checks:
            incident.post_mortem = self.draft_post_mortem(incident, checks)
        return incident

    def open_for(self, monitor_id: str) -> Incident | None:
        return next((i for i in self.incidents if i.monitor_id == monitor_id and i.open), None)

    def all_for(self, monitor_id: str) -> list[Incident]:
        return [i for i in self.incidents if i.monitor_id == monitor_id]

    def draft_post_mortem(self, incident: Incident, checks: list[CheckResult]) -> str:
        """Auto-generate a post-mortem draft from incident + check data."""
        affected_regions = sorted({c.region for c in checks if c.status == "down"})
        timeline = sorted(checks, key=lambda c: c.timestamp)
        lines = []
        lines.append(f"# Incident Post-Mortem (DRAFT)")
        lines.append(f"")
        lines.append(f"**Monitor:** {incident.monitor_id}")
        lines.append(f"**Started:** {incident.started_at.isoformat()}")
        lines.append(f"**Resolved:** {incident.resolved_at.isoformat() if incident.resolved_at else 'OPEN'}")
        lines.append(f"**Duration:** {incident.duration_min} minutes")
        lines.append(f"**Cause:** {incident.cause}")
        lines.append(f"**Affected regions:** {', '.join(affected_regions) or 'unknown'}")
        lines.append(f"")
        lines.append(f"## Timeline")
        for c in timeline[-20:]:
            lines.append(f"- {c.timestamp.isoformat()} [{c.region}] {c.status} "
                         f"({c.response_time_ms}ms) {c.error or ''}".rstrip())
        lines.append(f"")
        lines.append(f"## Impact")
        lines.append(f"- Downtime: {incident.duration_min} minutes")
        lines.append(f"")
        lines.append(f"## Root Cause (fill in)")
        lines.append(f"_To be completed by on-call engineer._")
        lines.append(f"")
        lines.append(f"## Action Items")
        lines.append(f"- [ ] Investigate root cause")
        lines.append(f"- [ ] Add monitoring for contributing factor")
        lines.append(f"- [ ] Update runbook")
        lines.append(f"")
        lines.append(f"_Auto-generated by Uptime Pro. Review before publishing._")
        return "\n".join(lines)

    def sla_breach(self, monitor_id: str, uptime_pct: float) -> bool:
        return uptime_pct < self.sla.target_uptime_pct

    def mttr(self, monitor_id: str) -> float:
        """Mean time to recovery in minutes."""
        resolved = [i for i in self.incidents
                    if i.monitor_id == monitor_id and i.resolved_at]
        if not resolved:
            return 0.0
        return round(sum(i.duration_min for i in resolved) / len(resolved), 1)

    def incident_frequency(self, monitor_id: str, days: int = 30) -> int:
        cutoff = datetime.utcnow() - timedelta(days=days)
        return len([i for i in self.incidents
                    if i.monitor_id == monitor_id and i.started_at >= cutoff])
